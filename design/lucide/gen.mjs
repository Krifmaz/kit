// Turns the Lucide icons named in icons.txt into the kit's icon sources:
//   crates/kit-leptos/src/lucide.rs   (the web: each icon's SVG elements, drawn in the kit's common <svg>)
//   android/kit-compose/src/main/java/dev/krifmaz/kit/compose/icons/KitIcons.kt   (Android: ImageVectors)
//
//   npm i --no-save lucide-static@0.460.0 && node design/lucide/gen.mjs [path to lucide-static/icons]
//
// Lucide is ISC-licensed (https://lucide.dev/license); the licence text is kept in design/lucide/LICENSE.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const src = process.argv[2] ?? path.join(process.cwd(), 'node_modules/lucide-static/icons');
const names = fs.readFileSync(path.join(here, 'icons.txt'), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));

const attrs = (s) => Object.fromEntries([...s.matchAll(/([a-z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v ?? 0);
const fmt = (v) => String(Math.round(v * 1000) / 1000);

// One element as path data (Compose draws paths only).
function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': { const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)]; return `M${fmt(cx - r)} ${fmt(cy)}a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(2 * r)} 0a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(-2 * r)} 0`; }
    case 'ellipse': { const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)]; return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0`; }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === 'polygon' ? d + 'Z' : d;
    }
    case 'rect': {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
      if (!rx) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(ry)}v${fmt(h - 2 * ry)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(ry)}h${fmt(-(w - 2 * rx))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(-ry)}v${fmt(-(h - 2 * ry))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(-ry)}Z`;
    }
    default: throw new Error(`${tag}: not an element the generator knows`);
  }
}

const icons = names.map((name) => {
  const svg = fs.readFileSync(path.join(src, `${name}.svg`), 'utf8');
  const els = [...svg.matchAll(/<(path|circle|ellipse|line|polyline|polygon|rect)\b([^>]*?)\/?>/g)].map((m) => ({ tag: m[1], a: attrs(m[2]) }));
  const web = els.map(({ tag, a }) => `<${tag} ${Object.entries(a).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
  return { name, web, paths: els.map(({ tag, a }) => toPath(tag, a)) };
});
const version = JSON.parse(fs.readFileSync(path.join(src, '../package.json'), 'utf8')).version;

let rs = `//! The Lucide icons the kit ships (lucide-static ${version}, ISC licence, https://lucide.dev): each icon's SVG
//! elements on Lucide's 24 × 24 grid, drawn in the kit's common \`<svg>\` (stroke 2, round ends, \`currentColor\`).
//! Generated by design/lucide/gen.mjs from design/lucide/icons.txt. Do not edit by hand.

/// The names, in order.
pub const NAMES: [&str; ${icons.length}] = [${icons.map((i) => `"${i.name}"`).join(', ')}];

/// The elements of Lucide icon \`name\` (\`""\` for a name the kit does not ship).
pub fn elements(name: &str) -> &'static str {
    match name {
${icons.map((i) => `        "${i.name}" => r#"${i.web}"#,`).join('\n')}
        _ => "",
    }
}
`;
fs.writeFileSync(path.join(root, 'crates/kit-leptos/src/lucide.rs'), rs);

// Long path data split into pieces of at most 120 characters (ktlint's line length).
const chunks = (d) => d.match(/.{1,120}/g);
const camel = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('').replace(/^(\d)/, 'I$1');
let kt = `// Generated by design/lucide/gen.mjs from design/lucide/icons.txt. Do not edit by hand.
// Lucide icons (lucide-static ${version}, ISC licence, https://lucide.dev).
package dev.krifmaz.kit.compose.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** The kit's icons: Lucide's stroked 24 × 24 outlines, the same set as the web's. Tint them with \`Icon(tint = …)\`. */
object KitIcons {
    private val cache = HashMap<String, ImageVector>()

    /** Every icon's path data, by Lucide name. */
    val PATHS: Map<String, List<String>> =
        mapOf(
${icons.map((i) => `            "${i.name}" to\n                listOf(\n${i.paths.map((p) => `                    ${chunks(p).map((c) => `"${c}"`).join(' +\n                        ')},`).join('\n')}\n                ),`).join('\n')}
        )

    /** The icon called [name] (a Lucide name, as on the web), or null when the kit does not ship it. */
    fun byName(name: String): ImageVector? {
        cache[name]?.let { return it }
        val paths = PATHS[name] ?: return null
        val builder =
            ImageVector.Builder(
                name = "lucide.$name",
                defaultWidth = 24.dp,
                defaultHeight = 24.dp,
                viewportWidth = 24f,
                viewportHeight = 24f,
            )
        for (d in paths) {
            builder.addPath(
                pathData = addPathNodes(d),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = 2f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
        return builder.build().also { cache[name] = it }
    }

${icons.map((i) => `    /** Lucide \`${i.name}\`. */\n    val ${camel(i.name)}: ImageVector get() = byName("${i.name}")!!`).join('\n\n')}
}
`;
const ktDir = path.join(root, 'android/kit-compose/src/main/java/dev/krifmaz/kit/compose/icons');
fs.mkdirSync(ktDir, { recursive: true });
fs.writeFileSync(path.join(ktDir, 'KitIcons.kt'), kt);
console.log(`wrote ${icons.length} icons`);
