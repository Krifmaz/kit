#!/usr/bin/env bash
# Puts visual QA's screenshots on a pull request: copies $OUT (scripts/visual-qa.cjs's folder) to pr-$PR/ on the
# repository's visual-qa branch (one commit, replaced each time, so the branch never grows), then writes or updates
# one comment on the PR with every page at every size and the report.
#   GH_TOKEN, GITHUB_REPOSITORY, PR, SHA, OUT   (set by the workflow)
set -euo pipefail

BRANCH=visual-qa
MARK='<!-- kit-visual-qa -->'
WORK="$(mktemp -d)"
git config --global user.name "github-actions[bot]"
git config --global user.email "41898282+github-actions[bot]@users.noreply.github.com"
URL="https://x-access-token:${GH_TOKEN}@github.com/${GITHUB_REPOSITORY}.git"

# the branch as it is, or a new one with nothing in it
if git clone --quiet --depth 1 --branch "$BRANCH" "$URL" "$WORK" 2> /dev/null; then
  :
else
  git init --quiet "$WORK"
  git -C "$WORK" checkout --quiet --orphan "$BRANCH"
  git -C "$WORK" remote add origin "$URL"
fi
rm -rf "${WORK:?}/pr-$PR"
mkdir -p "$WORK/pr-$PR"
cp -r "$OUT"/. "$WORK/pr-$PR/"
printf '# Visual QA screenshots\n\nMade by the kit CI for each pull request (pr-<number>/). Not code; replaced on every run.\n' > "$WORK/README.md"
git -C "$WORK" add -A
git -C "$WORK" commit --quiet -m "Visual QA screenshots"
# one commit only: the newest screenshots of every PR, nothing older
TREE=$(git -C "$WORK" rev-parse 'HEAD^{tree}')
ONE=$(git -C "$WORK" commit-tree "$TREE" -m "Visual QA screenshots (PR #$PR at ${SHA:0:7})")
git -C "$WORK" push --quiet --force origin "$ONE:refs/heads/$BRANCH"

RAW="https://github.com/${GITHUB_REPOSITORY}/blob/${ONE}/pr-${PR}"
{
  echo "$MARK"
  echo "### Visual QA for ${SHA:0:7}"
  echo
  echo "Every demo page at a phone (390×844), a tablet (820×1180) and a desktop (1440×900). The run fails on horizontal overflow or overlapping text."
  echo
  cat "$OUT/report.md"
  echo
  echo "| Page | Phone | Tablet | Desktop |"
  echo "|---|---|---|---|"
  for f in "$OUT"/phone/*.png; do
    name=$(basename "$f" .png)
    row="| $name |"
    for vp in phone tablet desktop; do
      if [ -f "$OUT/$vp/$name.png" ]; then
        row="$row <a href=\"$RAW/$vp/$name.png\"><img src=\"$RAW/$vp/$name.png?raw=true\" width=\"200\" alt=\"$name, $vp\"></a> |"
      else
        row="$row |"
      fi
    done
    echo "$row"
  done
  echo
  echo "---"
  echo "_Generated by the kit's visual QA (scripts/visual-qa.cjs)_"
} > "$WORK/comment.md"

ID=$(gh api "repos/$GITHUB_REPOSITORY/issues/$PR/comments?per_page=100" --paginate --jq ".[] | select(.body | startswith(\"$MARK\")) | .id" | head -n1)
if [ -n "$ID" ]; then
  gh api -X PATCH "repos/$GITHUB_REPOSITORY/issues/comments/$ID" -F "body=@$WORK/comment.md" > /dev/null
else
  gh api -X POST "repos/$GITHUB_REPOSITORY/issues/$PR/comments" -F "body=@$WORK/comment.md" > /dev/null
fi
echo "The screenshots are on PR #$PR."
